//! Ksymtab generator (risk R-D): parse the previously linked kernel ELF's
//! .symtab and emit OUT_DIR/ksymtab.rs with a fixed-size table so a second
//! link pass converges (the emitted bytes never change kernel layout).
//!
//! Convergence contract: the table always holds exactly KSYM_CAP entries
//! (padding entries have addr 0), so .rodata size is constant and symbol
//! addresses are identical between passes. The Makefile rebuilds until the
//! kernel hash stabilizes (<= 3 passes).
//!
//! Cargo layout note: OUT_DIR = <target>/<triple>/<profile>/build/<pkg>-<hash>/out,
//! and the kernel binary lands at <target>/<triple>/<profile>/kernel.

use std::env;
use std::fs;
use std::path::PathBuf;

const KSYM_CAP: usize = 2048;
const KSYM_NAME: usize = 56;

fn main() {
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    // Rerun when sources change (declaring any rerun-if path disables the
    // default "anything changed" behavior).
    println!("cargo:rerun-if-changed={}", manifest.join("src").display());
    println!(
        "cargo:rerun-if-changed={}",
        manifest.join("build.rs").display()
    );

    // Previous kernel ELF (out -> <pkg>-<hash> -> build -> <profile>).
    let kernel_elf = out_dir
        .ancestors()
        .nth(3)
        .expect("OUT_DIR depth")
        .join("kernel");
    println!("cargo:rerun-if-changed={}", kernel_elf.display());

    let mut syms: Vec<(u64, String, u8)> = Vec::new();
    if env::var("CARGO_CFG_TARGET_ARCH").as_deref() == Ok("x86_64") {
        if let Ok(bytes) = fs::read(&kernel_elf) {
            syms = parse_symbols(&bytes).unwrap_or_default();
        }
    }

    if syms.len() > KSYM_CAP {
        panic!(
            "kernel symbol count {} exceeds KSYM_CAP {}",
            syms.len(),
            KSYM_CAP
        );
    }
    // Deterministic order: by address, then name; drop same-address aliases
    // after the first (prefer shorter names for readable oops lines).
    syms.sort_by(|a, b| {
        a.0.cmp(&b.0)
            .then(a.1.len().cmp(&b.1.len()))
            .then(a.1.cmp(&b.1))
    });
    syms.dedup_by(|a, b| a.0 == b.0);

    let mut out = String::with_capacity(64 * KSYM_CAP);
    out.push_str("// @generated by kernel/build.rs — do not edit.\n");
    out.push_str(&format!("pub const KSYM_COUNT: usize = {};\n", syms.len()));
    out.push_str("pub static KSYM_TABLE: [Ksym; KSYM_CAP] = [\n");
    for (addr, name) in syms
        .iter()
        .map(|(a, n, _)| (*a, n.as_str()))
        .chain(std::iter::repeat((0u64, "")).take(KSYM_CAP - syms.len()))
    {
        let mut bytes = [0u8; KSYM_NAME];
        let n = name.len().min(KSYM_NAME - 1);
        bytes[..n].copy_from_slice(&name.as_bytes()[..n]);
        out.push_str(&format!(
            "    Ksym {{ addr: {}, name: {} }},\n",
            addr,
            byte_literal(&bytes)
        ));
    }
    out.push_str("];\n");

    let dest = out_dir.join("ksymtab.rs");
    if fs::read_to_string(&dest).as_deref().ok() != Some(out.as_str()) {
        fs::write(&dest, &out).expect("write ksymtab.rs");
    }

    stage_user_images(&out_dir);
}

/// Emit a `[u8; KSYM_NAME]` literal as a byte-string with padding NULs.
fn byte_literal(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() + 12);
    s.push_str("*b\"");
    for &b in bytes {
        match b {
            b'"' => s.push_str("\\\""),
            b'\\' => s.push_str("\\\\"),
            0x20..=0x7e => s.push(b as char),
            _ => s.push_str(&format!("\\x{:02x}", b)),
        }
    }
    s.push('"');
    s
}

/// Minimal ELF64 LE .symtab walk: FUNC/OBJECT/NOTYPE with a nonzero value
/// and a defined section index.
fn parse_symbols(b: &[u8]) -> Option<Vec<(u64, String, u8)>> {
    if b.len() < 64 || &b[0..4] != b"\x7fELF" || b[4] != 2 || b[5] != 1 {
        return None;
    }
    let rd16 = |o: usize| u16::from_le_bytes([b[o], b[o + 1]]);
    let rd64 = |o: usize| {
        let mut v = [0u8; 8];
        v.copy_from_slice(&b[o..o + 8]);
        u64::from_le_bytes(v)
    };
    let e_shoff = rd64(0x28) as usize;
    let e_shentsize = rd16(0x3a) as usize;
    let e_shnum = rd16(0x3c) as usize;
    if e_shoff == 0 || e_shentsize < 64 || e_shnum == 0 {
        return None;
    }
    let sh = |i: usize| -> Option<&[u8]> {
        let o = e_shoff.checked_add(i * e_shentsize)?;
        b.get(o..o + 64)
    };
    let mut out = Vec::new();
    for i in 0..e_shnum {
        let sec = sh(i)?;
        if rd32_at(sec, 4) != 2 {
            continue; // SHT_SYMTAB
        }
        let symoff = rd64_at(sec, 0x18) as usize;
        let symsize = rd64_at(sec, 0x20) as usize;
        let strtab = sh(rd32_at(sec, 0x28) as usize)?;
        let stroff = rd64_at(strtab, 0x18) as usize;
        let strsize = rd64_at(strtab, 0x20) as usize;
        for k in 0..symsize / 24 {
            let o = symoff + k * 24;
            let sym = b.get(o..o + 24)?;
            let st_name = u32::from_le_bytes([sym[0], sym[1], sym[2], sym[3]]);
            let st_info = sym[4];
            let st_shndx = u16::from_le_bytes([sym[6], sym[7]]);
            let st_value = u64::from_le_bytes(sym[8..16].try_into().unwrap());
            let typ = st_info & 0xf;
            let keep = matches!(typ, 1 | 2) || (typ == 0 && st_value != 0);
            if !keep || st_value == 0 || st_shndx == 0 || st_name == 0 {
                continue;
            }
            let so = stroff + st_name as usize;
            if so >= stroff + strsize {
                continue;
            }
            let end = b[so..stroff + strsize]
                .iter()
                .position(|&c| c == 0)
                .map(|p| so + p)
                .unwrap_or(stroff + strsize);
            let name = String::from_utf8_lossy(&b[so..end]).into_owned();
            if name.is_empty() {
                continue;
            }
            out.push((st_value, name, typ));
        }
        break; // first symtab only
    }
    Some(out)
}

fn rd32_at(sec: &[u8], o: usize) -> u32 {
    u32::from_le_bytes(sec[o..o + 4].try_into().unwrap())
}
fn rd64_at(sec: &[u8], o: usize) -> u64 {
    u64::from_le_bytes(sec[o..o + 8].try_into().unwrap())
}

/// S3 user images: stage the linked user ELFs into OUT_DIR/userimg so the
/// kernel can include_bytes! them. Source: MINIOS_USER_IMG_DIR (Makefile,
/// points at the user crate's target release dir); missing files become
/// empty placeholders so a bare `cargo check` of the kernel still works.
fn stage_user_images(out_dir: &std::path::Path) {
    use std::path::Path;

    let dir = out_dir.join("userimg");
    fs::create_dir_all(&dir).expect("mkdir OUT_DIR/userimg");
    let src_dir = env::var("MINIOS_USER_IMG_DIR").unwrap_or_default();
    let src_root = Path::new(&src_dir);
    println!("cargo:rerun-if-env-changed=MINIOS_USER_IMG_DIR");
    if src_dir.is_empty() {
        println!("cargo:warning=MINIOS_USER_IMG_DIR unset; embedding empty user images");
    } else {
        println!("cargo:rerun-if-changed={}", src_root.display());
    }
    for name in ["m1r-suite", "m1r-exec-child"] {
        let src = src_root.join(name);
        let dst = dir.join(name);
        let bytes = match fs::read(&src) {
            Ok(b) => b,
            Err(_) => {
                if !src_dir.is_empty() {
                    println!(
                        "cargo:warning=user image {} not found at {}",
                        name,
                        src.display()
                    );
                }
                Vec::new()
            }
        };
        // Only rewrite on change: content-identical reruns keep the
        // convergence loop calm.
        let _ = fs::write(&dst, &bytes);
    }
}
